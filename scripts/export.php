<?php
declare(strict_types=1);

// Render the existing PHP templates into a static directory for Vercel.
// The worker runs in its own process so template variables never leak between pages.
$projectRoot = dirname(__DIR__);
if (($argv[1] ?? '') === '--render') {
    $entry = $argv[2] ?? '';
    if (!preg_match('/^[a-z-]+\.php$/', $entry) || !is_file($projectRoot.'/'.$entry)) {
        fwrite(STDERR, "Unknown page.\n");
        exit(1);
    }
    parse_str($argv[3] ?? '', $_GET);
    $_SERVER['REQUEST_METHOD'] = 'GET';
    $_SERVER['SCRIPT_NAME'] = '/'.$entry;
    $_SERVER['REQUEST_URI'] = '/'.$entry.(empty($_GET) ? '' : '?'.http_build_query($_GET));
    chdir($projectRoot);
    require $projectRoot.'/'.$entry;
    exit;
}

require $projectRoot.'/data/content.php';
$output = $projectRoot.'/public';
$marker = $output.'/.php-static-export';
if (file_exists($output)) {
    if (is_link($output) || realpath($output) !== realpath($projectRoot).DIRECTORY_SEPARATOR.'public' || !is_file($marker)) {
        throw new RuntimeException('Refusing to replace an unmanaged public directory.');
    }
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($output, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($files as $file) {
        if ($file->isDir() && !$file->isLink()) {
            rmdir($file->getPathname());
        } else {
            unlink($file->getPathname());
        }
    }
} else {
    mkdir($output, 0755, true);
}
file_put_contents($marker, "Generated by scripts/export.php. Edit the PHP source, then export again.\n");

function renderPage(string $entry, array $query = []): string {
    $process = proc_open([PHP_BINARY, '-d', 'display_errors=stderr', __FILE__, '--render', $entry, http_build_query($query)], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
    if (!is_resource($process)) throw new RuntimeException('Could not start PHP renderer.');
    $html = stream_get_contents($pipes[1]);
    $errors = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $status = proc_close($process);
    if ($status !== 0 || $errors !== '' || !str_contains($html, '</html>')) {
        throw new RuntimeException('Failed rendering '.$entry.': '.$errors);
    }
    return $html;
}

$aliases = ['collabs.php' => 'contact.php', 'consulting.php' => 'contact.php'];
foreach ($sectionVisibility as $pageName => $visible) {
    if (!$visible && is_file($projectRoot.'/'.$pageName.'.php')) $aliases[$pageName.'.php'] = 'index.php';
}
$staticLinks = [];
foreach (glob($projectRoot.'/*.php') as $sourceFile) {
    $entry = basename($sourceFile);
    if ($entry === 'post.php') continue;
    $staticLinks[$entry] = basename($aliases[$entry] ?? $entry, '.php').'.html';
}
foreach ($articles as $article) {
    $staticLinks['post.php?slug='.$article['slug']] = 'post-'.$article['slug'].'.html';
}
$rewrites = [];
$redirects = [];
foreach ($aliases as $from => $to) {
    $redirects[] = ['source' => '/'.$from, 'destination' => '/'.$to, 'permanent' => false];
}

$pageCount = 0;
foreach (glob($projectRoot.'/*.php') as $sourceFile) {
    $entry = basename($sourceFile);
    if (isset($aliases[$entry]) || $entry === 'post.php') continue;
    $filename = basename($entry, '.php').'.html';
    file_put_contents($output.'/'.$filename, strtr(renderPage($entry), $staticLinks));
    $rewrites[] = ['source' => '/'.$entry, 'destination' => '/'.$filename];
    $pageCount++;
}
foreach ($articles as $article) {
    $slug = $article['slug'];
    if (!preg_match('/^[a-z0-9-]+$/', $slug)) throw new RuntimeException('Invalid article slug.');
    $filename = 'post-'.$slug.'.html';
    file_put_contents($output.'/'.$filename, strtr(renderPage('post.php', ['slug' => $slug]), $staticLinks));
    $rewrites[] = ['source' => '/post.php', 'has' => [['type' => 'query', 'key' => 'slug', 'value' => $slug]], 'destination' => '/'.$filename];
    $pageCount++;
}
// No catch-all rewrite: unknown pages/slugs keep a real HTTP 404 status.
file_put_contents($output.'/404.html', strtr(renderPage('post.php'), $staticLinks));

$assetRoot = $projectRoot.'/assets';
$assets = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($assetRoot, FilesystemIterator::SKIP_DOTS));
foreach ($assets as $asset) {
    if (!$asset->isFile() || $asset->isLink() || strtolower($asset->getExtension()) === 'php') continue;
    $relative = substr($asset->getPathname(), strlen($assetRoot) + 1);
    $destination = $output.'/assets/'.$relative;
    if (!is_dir(dirname($destination))) mkdir(dirname($destination), 0755, true);
    if (strtolower($asset->getExtension()) === 'js') {
        file_put_contents($destination, strtr(file_get_contents($asset->getPathname()), $staticLinks));
    } else {
        copy($asset->getPathname(), $destination);
    }
}
$config = [
    '$schema' => 'https://openapi.vercel.sh/vercel.json',
    'framework' => null,
    'buildCommand' => '',
    'installCommand' => '',
    'outputDirectory' => 'public',
    'cleanUrls' => false,
    'trailingSlash' => false,
    'redirects' => $redirects,
    'rewrites' => $rewrites,
];
file_put_contents($projectRoot.'/vercel.json', json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n");
echo 'Exported '.$pageCount." pages plus the 404 page and assets to public/.\n";
echo "Vercel configuration written to vercel.json. No PHP runtime is needed in production.\n";
